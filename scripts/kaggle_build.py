"""Package a list of yambda_bench.py runs as a private Kaggle GPU script kernel.

The kernel embeds the two Yambda scripts, mounts the private dataset with listens_50m.parquet,
and runs the jobs on a queue with one worker per visible GPU (T4 x2 gives two runs at a time).

Usage:
  python scripts/kaggle_build.py --slug yambda-step1 --jobs "--model sasrec --d 64" "--model sasrec --d 128" ...
  uvx kaggle kernels push -p kaggle/<slug>
  uvx kaggle kernels output dnnguynhng/<slug> -p runs/kaggle/<slug>
"""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
USER = "dnnguynhng"
DATASET = f"{USER}/yambda-50m-listens"

RUNNER = '''"""Generated by scripts/kaggle_build.py; edit the repo, not this file."""
import glob
import os
import queue
import shlex
import subprocess
import sys
import threading
from pathlib import Path

import torch

SOURCES = {sources}
JOBS = {jobs}

code = Path("/kaggle/working/code")
code.mkdir(parents=True, exist_ok=True)
for name, text in SOURCES.items():
    (code / name).write_text(text)
data = Path(glob.glob("/kaggle/input/**/listens_50m.parquet", recursive=True)[0]).parent
logs = Path("/kaggle/working/logs"); logs.mkdir(exist_ok=True)
subprocess.run(["nvidia-smi"], check=False)

jobs = queue.Queue()
for j in JOBS:
    jobs.put(j)
failed = []


def worker(gpu):
    env = dict(os.environ, CUDA_VISIBLE_DEVICES=str(gpu), YAMBDA_DIR=str(data), RUNS_DIR="/kaggle/working/runs")
    while True:
        try:
            j = jobs.get_nowait()
        except queue.Empty:
            return
        name = j.replace("--", "").replace(" ", "_")
        print(f"[gpu{{gpu}}] start {{j}}", flush=True)
        with open(logs / f"{{name}}.log", "w") as f:
            r = subprocess.run([sys.executable, "-u", "yambda_bench.py", *shlex.split(j)], cwd=code, env=env,
                               stdout=f, stderr=subprocess.STDOUT)
        print(f"[gpu{{gpu}}] exit {{r.returncode}} {{j}}", flush=True)
        print((logs / f"{{name}}.log").read_text()[-1500:], flush=True)
        if r.returncode:
            failed.append(j)


threads = [threading.Thread(target=worker, args=(g,)) for g in range(max(1, torch.cuda.device_count()))]
for th in threads:
    th.start()
for th in threads:
    th.join()
print("failed:", failed, flush=True)
'''


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--slug", required=True)
    ap.add_argument("--jobs", nargs="+", required=True)
    a = ap.parse_args()
    sources = {n: (ROOT / "scripts" / n).read_text() for n in ("yambda_seq_pilot.py", "yambda_bench.py")}
    out = ROOT / "kaggle" / a.slug
    out.mkdir(parents=True, exist_ok=True)
    (out / "run.py").write_text(RUNNER.format(sources=repr(sources), jobs=repr(a.jobs)))
    meta = {
        "id": f"{USER}/{a.slug}", "title": a.slug, "code_file": "run.py", "language": "python",
        "kernel_type": "script", "is_private": "true", "enable_gpu": "true", "enable_tpu": "false",
        "enable_internet": "false", "dataset_sources": [DATASET], "competition_sources": [],
        "kernel_sources": [], "model_sources": [],
    }
    (out / "kernel-metadata.json").write_text(json.dumps(meta, indent=2))
    print(f"wrote {out}: {len(a.jobs)} jobs")


if __name__ == "__main__":
    main()
